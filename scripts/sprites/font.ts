export const GLYPH_W = 3;
export const GLYPH_H = 5;

export function textWidth(text: string, scale = 1, tracking = 1): number {
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

export function drawText(
  dst: Raster,
  text: string,
  x: number,
  y: number,
  color: Rgba,
  scale = 1,
  tracking = 1,
): void {
  let cx = x;
  for (const raw of text.toUpperCase()) {
    const rows = (GLYPHS[raw] ?? GLYPHS['?']).split('|');
    for (let r = 0; r < rows.length; r++) {
      for (let c = 0; c < rows[r].length; c++) {
        if (rows[r][c] !== '#') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            setPixel(dst, cx + c * scale + sx, y + r * scale + sy, color);
          }
        }
      }
    }
    cx += (GLYPH_W + tracking) * scale;
  }
}
